const POSTS_START = (window.QS_CONFIG && QS_CONFIG.postsStart) || '2026-11-02'; // يوم اثنين
/* المنشورات التي حان نشرها حتى اليوم: كل اثنين وجمعة منشور جديد بالترتيب */
function weeklyPosts() {
  const out = [], t = today(); let d = POSTS_START, i = 0;
  while (d <= t && i < 400) {
    const wd = new Date(d + 'T12:00:00Z').getUTCDay();
    if (wd == 1 || wd == 5) { const p = WEEKLY[i % WEEKLY.length]; out.unshift({ cat: p[0], title: p[1], body: p[2], d, day: wd == 1 ? 'الاثنين' : 'الجمعة' }); i++; }
    d = addDays(d, 1);
  }
  return out;
}
